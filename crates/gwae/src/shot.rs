//! Pane screenshot: grid cells → RGBA → PNG.
//!
//! Used by the image clipboard (`⌥+Shift+c`, `image_clipboard = true`).
//! Renders the *visible* grid exactly as the TUI paints it, but to pixels
//! instead of terminal cells: each cell becomes an 8×16 pixel tile drawn with
//! an embedded 8×8 mono bitmap font (VT `font8x8_basic`, public domain VGA).
//!
//! No external image or font crates: the PNG is encoded by hand (IHDR/IDAT/IEND
//! with a stored-deflate zlib stream) so the feature has zero heavy
//! dependencies and builds on every target gwae does.

